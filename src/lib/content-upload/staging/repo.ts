// The data access of the content upload as one interface.
//
// Services (runs, announce, signed urls, complete, queue, cleanup) only talk to
// UploadRepo. Two implementations exist:
//
//   repo-pg.ts                      SQL through Drizzle, what the routes use
//   tests/helpers/memoryUploadRepo  the same behavior in memory, what the unit
//                                   tests use (and what the contract test in
//                                   tests/unit/lib/content-upload/repo-contract.ts
//                                   holds to the same rules as the SQL one)
//
// Every method that changes a status is a conditional update: it names the
// status it expects and does nothing, and says so, when the row is in another
// one. That is what keeps two calls at the same time from doing a step twice.

import type {
  Candidate,
  AnnouncePlan,
} from '@/lib/content-upload/staging/announce';
import type {
  FilePatch,
  FileRow,
  RunProgress,
  RunRow,
} from '@/lib/content-upload/staging/types';
import type {
  FileStatus,
  RunStatus,
} from '@/lib/content-upload/staging/status';

export interface CreateRunInput {
  /** Generated by the server: the storage folder of the run is made from it. */
  id: string;
  catalogId: string;
  createdById: string;
  label: string;
  kiEnabled: boolean;
  storagePrefix: string;
}

export type CreateRunResult =
  | { ok: true; run: RunRow }
  | { ok: false; reason: 'TOO_MANY_ACTIVE_RUNS' };

export type AnnounceRepoResult =
  | { ok: true; plan: AnnouncePlan }
  | { ok: false; reason: 'RUN_NOT_FOUND' }
  | { ok: false; reason: 'RUN_STATE'; status: RunStatus };

export interface ClaimOptions {
  /** Claim files in these states only (the states that have a step). */
  statuses: readonly FileStatus[];
  limit: number;
  /** How long the claim holds, in seconds (fractions allowed). */
  lockSeconds: number;
  /** Files with this many attempts or more are not claimed any more. */
  maxAttempts: number;
}

export interface QueueState {
  /** Files that are announced but not yet reported as uploaded. */
  announced: number;
  /** Files a pump could claim right now. */
  claimable: number;
  /** Files with a claim that has not expired. */
  locked: number;
}

export interface FinishOptions {
  code?: string | null;
  patch?: FilePatch;
}

export interface TransitionOptions {
  code?: string | null;
  /** Set completed_at (the file was reported as uploaded). */
  completed?: boolean;
  /** Write the marker that the object is gone from the bucket. */
  objectDeleted?: boolean;
}

export interface UrlRequestDecision {
  allowed: boolean;
  retryAfterSec: number;
  /** Requests counted in the current window. */
  count: number;
}

export interface UploadRepo {
  // ---- runs --------------------------------------------------------------
  /** Id of the catalog with this code (active or not), or null. */
  catalogIdByCode(code: string): Promise<string | null>;
  /** Creates a run unless the person already has `maxActive` active ones. */
  createRun(input: CreateRunInput, maxActive: number): Promise<CreateRunResult>;
  getRun(id: string): Promise<RunRow | null>;
  /** Newest first. Without `createdById` all runs. */
  listRuns(options: { createdById?: string; limit: number }): Promise<RunRow[]>;
  /**
   * Moves the run from one of `from` to `to` (a transition of the model), or
   * returns null if it is in none of them. `purgeAfterDays` sets purge_after.
   */
  transitionRun(
    id: string,
    from: readonly RunStatus[],
    to: RunStatus,
    options?: { purgeAfterDays?: number }
  ): Promise<RunRow | null>;
  runProgress(runId: string): Promise<RunProgress>;
  /** Marks activity: sets updated_at to now (an idle run is cleaned up after 30 days). */
  touchRun(id: string): Promise<void>;

  // ---- files -------------------------------------------------------------
  /** Writes the plan of an announce in one transaction under a lock on the run. */
  announce(
    runId: string,
    candidates: readonly Candidate[]
  ): Promise<AnnounceRepoResult>;
  listFiles(
    runId: string,
    options: { offset: number; limit: number }
  ): Promise<FileRow[]>;
  /** Only files of this run, in the order of the ids that exist. */
  getFiles(runId: string, ids: readonly string[]): Promise<FileRow[]>;
  /** Moves one file of the run from `from` to `to`, or null if it is not in `from`. */
  transitionFile(
    runId: string,
    fileId: string,
    from: FileStatus,
    to: FileStatus,
    options?: TransitionOptions
  ): Promise<FileRow | null>;

  // ---- queue -------------------------------------------------------------
  /**
   * Takes up to `limit` files of the run in the claimable states, in one atomic
   * statement: a new claim_id, locked_until in the future, attempts + 1. A file
   * that another call holds is skipped, never waited for.
   */
  claimFiles(runId: string, options: ClaimOptions): Promise<FileRow[]>;
  /**
   * Ends a claim with a new status. Written only if the claim_id is still the
   * one of the caller and the status is `from`. Resets attempts and the lock.
   */
  finishClaim(
    fileId: string,
    claimId: string,
    from: FileStatus,
    to: FileStatus,
    options?: FinishOptions
  ): Promise<boolean>;
  /**
   * Gives a claim back for another attempt (attempts stays as counted). With a
   * delay the file stays locked that long, so the retry is a later call and not
   * the next batch of the same one.
   */
  releaseClaim(
    fileId: string,
    claimId: string,
    delaySeconds?: number
  ): Promise<boolean>;
  /**
   * Fails the files of the run that ran out of attempts and whose lock has
   * expired (the call that held them died). Returns how many.
   */
  failExhausted(
    runId: string,
    statuses: readonly FileStatus[],
    maxAttempts: number,
    code: string
  ): Promise<number>;
  queueState(
    runId: string,
    statuses: readonly FileStatus[],
    maxAttempts: number
  ): Promise<QueueState>;

  // ---- rate limit --------------------------------------------------------
  /** Counts one request for signed upload urls of this person (database counter). */
  reserveUrlRequest(profileId: string): Promise<UrlRequestDecision>;

  // ---- cleanup -----------------------------------------------------------
  /** announced -> expired for files older than `hours`. Returns how many. */
  expireStaleAnnounced(hours: number, limit: number): Promise<number>;
  /**
   * Files whose object has to go: rejected or expired files, files of discarded
   * runs, files of applied runs past purge_after, each without the marker that
   * the object is gone. Never merged copies. With `runId` only that run.
   */
  filesNeedingObjectRemoval(limit: number, runId?: string): Promise<FileRow[]>;
  markObjectsDeleted(fileIds: readonly string[]): Promise<void>;
  /**
   * Discards runs that were never applied and idle for `idleDays` (purge_after
   * is set `rowsDays` ahead). An applied run is never touched. Returns the ids.
   */
  discardStaleRuns(
    idleDays: number,
    rowsDays: number,
    limit: number
  ): Promise<string[]>;
  /** Deletes discarded runs past purge_after whose objects are all gone. */
  deleteRunsPastPurge(limit: number): Promise<number>;
  /** Which of these storage paths belong to a file row. */
  knownStoragePaths(paths: readonly string[]): Promise<Set<string>>;
}
